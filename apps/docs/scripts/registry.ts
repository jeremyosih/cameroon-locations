/**
 * Builds the shadcn registry served at `/r/*.json`.
 *
 * 1. Reads `registry.json` (the committed source of truth).
 * 2. For items with `"meta": { "vendor": "<package src dir>" }`, copies the
 *    listed package sources into `registry/generated/<item>/`, follows their
 *    relative imports, and replaces `src/data/*` modules with plain literal
 *    data, so the item works without the npm package.
 * 3. Writes the expanded registry to `registry/generated/registry.json` and
 *    runs `shadcn build` into `public/r`.
 * 4. Replaces `{{SITE_URL}}` in the output with `SITE_URL` from `src/site.ts`.
 *
 * Run from `apps/docs`: `bun scripts/registry.ts`.
 */
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { SITE_URL } from "../src/site";

const ROOT = resolve(import.meta.dir, "..");
const GENERATED = join(ROOT, "registry/generated");
const OUTPUT = join(ROOT, "public/r");
const TOKEN = "{{SITE_URL}}";

interface RegistryFile {
  path: string;
  type: string;
  target?: string;
}

interface RegistryItem {
  name: string;
  type: string;
  files?: RegistryFile[];
  meta?: { vendor?: string; target?: string; [key: string]: unknown };
  [key: string]: unknown;
}

interface Registry {
  items: RegistryItem[];
  [key: string]: unknown;
}

/** Type annotations for known data exports. */
const DATA_TYPES: Record<string, string> = {
  regions: "readonly Region[]",
  divisions: "readonly Division[]",
  arrondissements: "readonly Arrondissement[]",
  cantons: "readonly Canton[]",
  villages: "readonly Village[]",
  pollingStations: "readonly PollingStation[]",
  councilSummaries: "readonly CouncilElectoralSummary[]",
  metadata: "DatasetMetadata",
};

const SPECIFIER =
  /(?:import|export)\s[^"']*?from\s*["']([^"']+)["']|import\s*\(?\s*["']([^"']+)["']/g;

function specifiers(source: string): string[] {
  return [...source.matchAll(SPECIFIER)]
    .map((m) => m[1] ?? m[2])
    .filter((s): s is string => s !== undefined);
}

function resolveModule(from: string, spec: string): string | undefined {
  const base = resolve(dirname(from), spec);
  const candidates = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    join(base, "index.ts"),
  ];
  return candidates.find((c) => existsSync(c) && !c.endsWith("/"));
}

function isSerializable(value: unknown): boolean {
  if (value === null) return true;
  const t = typeof value;
  if (t === "string" || t === "number" || t === "boolean") return true;
  if (Array.isArray(value)) return value.every(isSerializable);
  if (t === "object")
    return Object.values(value as object).every(isSerializable);
  return false;
}

/** `src/data/*.ts` as literal data, or `undefined` if it isn't pure data. */
async function literalDataModule(file: string): Promise<string | undefined> {
  const mod = (await import(pathToFileURL(file).href)) as Record<
    string,
    unknown
  >;
  const entries = Object.entries(mod);
  if (!entries.every(([, v]) => isSerializable(v))) return undefined;
  const typeNames = new Set<string>();
  const body = entries.map(([name, value]) => {
    const type = DATA_TYPES[name];
    for (const t of type?.match(/[A-Z]\w+/g) ?? []) typeNames.add(t);
    const annotation = type ? `: ${type}` : "";
    return `export const ${name}${annotation} = deepFreeze(${JSON.stringify(value)});`;
  });
  const imports =
    typeNames.size > 0
      ? `import type { ${[...typeNames].sort().join(", ")} } from "../types";\n\n`
      : "";
  return `// Generated by apps/docs/scripts/registry.ts from cameroon-locations. Do not edit.
${imports}function deepFreeze<T>(value: T): T {
  if (value && typeof value === "object") {
    for (const v of Object.values(value)) deepFreeze(v);
    Object.freeze(value);
  }
  return value;
}

${body.join("\n\n")}
`;
}

/** Copies `entries` and everything they import into `outDir`. */
async function vendor(
  srcDir: string,
  entries: readonly string[],
  outDir: string,
): Promise<string[]> {
  const queue = entries.map((e) => resolve(srcDir, e));
  const seen = new Set<string>();
  const written: string[] = [];

  while (queue.length > 0) {
    const file = queue.shift() as string;
    if (seen.has(file)) continue;
    seen.add(file);

    const rel = relative(srcDir, file);
    if (rel.startsWith("..")) {
      throw new Error(
        `registry: ${file} is outside ${srcDir}. Import it from a src/data module so it can be inlined.`,
      );
    }
    const out = join(outDir, rel);
    mkdirSync(dirname(out), { recursive: true });

    if (rel.startsWith("data/")) {
      const literal = await literalDataModule(file);
      if (literal !== undefined) {
        writeFileSync(out, literal);
        written.push(out);
        if (literal.includes('from "../types"')) {
          queue.push(join(srcDir, "types.ts"));
        }
        continue;
      }
    }

    const source = readFileSync(file, "utf8");
    writeFileSync(out, source);
    written.push(out);
    for (const spec of specifiers(source)) {
      if (!spec.startsWith(".")) continue;
      const target = resolveModule(file, spec);
      if (!target)
        throw new Error(`registry: cannot resolve ${spec} in ${file}`);
      queue.push(target);
    }
  }
  return written.sort();
}

async function main() {
  const registry = JSON.parse(
    readFileSync(join(ROOT, "registry.json"), "utf8"),
  ) as Registry;

  rmSync(GENERATED, { recursive: true, force: true });
  mkdirSync(GENERATED, { recursive: true });

  for (const item of registry.items) {
    const vendorDir = item.meta?.vendor;
    if (!vendorDir) continue;
    const srcDir = resolve(ROOT, vendorDir);
    const outDir = join(GENERATED, item.name);
    const entries = (item.files ?? []).map((f) => f.path);
    const files = await vendor(srcDir, entries, outDir);
    const targetDir = item.meta?.target ?? `lib/${item.name}`;
    item.files = files.map((file) => {
      const rel = relative(outDir, file);
      return {
        path: relative(ROOT, file),
        type: item.type,
        target: `${targetDir}/${rel}`,
      };
    });
    const { vendor: _vendor, target: _target, ...meta } = item.meta ?? {};
    item.meta = Object.keys(meta).length > 0 ? meta : undefined;
    console.log(`registry: ${item.name} (${files.length} files)`);
  }

  const expanded = join(GENERATED, "registry.json");
  writeFileSync(expanded, `${JSON.stringify(registry, null, 2)}\n`);

  rmSync(OUTPUT, { recursive: true, force: true });
  const result = spawnSync(
    process.execPath,
    [
      "x",
      "shadcn",
      "build",
      relative(ROOT, expanded),
      "--output",
      relative(ROOT, OUTPUT),
    ],
    { cwd: ROOT, stdio: "inherit" },
  );
  if (result.status !== 0) {
    throw new Error(`shadcn build failed (${result.status ?? result.error})`);
  }

  for (const name of readdirSync(OUTPUT)) {
    if (!name.endsWith(".json")) continue;
    const file = join(OUTPUT, name);
    const json = readFileSync(file, "utf8");
    if (json.includes(TOKEN)) {
      writeFileSync(file, json.replaceAll(TOKEN, SITE_URL));
    }
  }
}

await main();
